"""Generate `web/data.js` from the tracked measurements.

    uv run python src/exercises/07-model-embeddings-internals/tools/build_web_data.py

`results/measurements.json` is the single source for every number the page renders. The page never
hard-codes one, so a figure on the site cannot drift from the measurement that produced it — which
is the failure this repo has paid for more than any other.

Unlike `build_notebook.py`, this file is TRACKED. It is not course material in another form; it is
the build step for a published artifact, and CI has to be able to check the page it produces.
"""

import json
from pathlib import Path

EXERCISE = Path(__file__).resolve().parents[1]
SOURCE = EXERCISE / "results" / "measurements.json"
OUT = EXERCISE / "web" / "data.js"

BANNER = """\
// GENERATED by tools/build_web_data.py from results/measurements.json — do not edit by hand.
//
// Every number rendered by this page comes from here, and everything here was measured. Editing
// this file directly would let the page disagree with the evidence that produced it; regenerate
// instead:
//
//     uv run python src/exercises/07-model-embeddings-internals/tools/build_web_data.py
"""


def main() -> int:
    """Write `web/data.js` from the measurements, and report what was written."""
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    body = json.dumps(data, indent=2, ensure_ascii=False)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        f"{BANNER}\nexport const M = Object.freeze({body});\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(EXERCISE)}  ({len(body):,} chars, {len(data)} top-level keys)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

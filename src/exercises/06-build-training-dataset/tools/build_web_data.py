"""Derive the explainer's data bundle from the run, so no figure on the page is typed by hand.

**Why this exists rather than a hand-written `data.js`.** This repo's most expensive recurring
defect is a sentence stating a number next to a correct generated table: the table looks maintained
and only the sentence is wrong, so a reader believes the sentence. A web page is the worst version
of that — it is read far more often than any Markdown file, and nothing tests a number inside a
`<script>` block.

So every figure the page renders comes from `submission_artifacts/` and `results/`, which are
written by `run_demo.py` and `tools/build_corpus.py`. If a run changes, the page changes with it or
this script fails. Nothing is copied from memory.

**What it deliberately does not do.** It does not read the ledger to recompute anything — that is
`verify.py`'s job, and doing it here would put a third implementation of the same arithmetic in the
repo. It reads what the bundle already published, and the auditor is what says those figures are
true.

Run it::

    uv run python src/exercises/06-build-training-dataset/tools/build_web_data.py
    uv run python .../build_web_data.py --check   # fail if web/data.js is stale
"""

import argparse
import json
import logging
import sys
from pathlib import Path

EXERCISE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(EXERCISE / "src"))

from trainingdata import spec  # noqa: E402

logger = logging.getLogger("build_web_data")

BUNDLE_DIR = EXERCISE / "submission_artifacts"
RESULTS_DIR = EXERCISE / "results"
WEB_DIR = EXERCISE / "web"

#: Preamble on the generated file, so nobody edits it by hand and loses the edit on the next run.
HEADER = """/* Generated by `tools/build_web_data.py` — do not edit.
 *
 * Every figure this page renders comes from submission_artifacts/ and results/, which run_demo.py
 * and build_corpus.py wrote. A number typed here by hand would survive every test in the repo and
 * be read more often than any of them, which is why none of them are.
 */
"""


def _value(value, unit: str, provenance: str = "measured", source: str = "") -> dict:
    """Wrap a figure in the shape `renderNumber` requires.

    `num.js` throws on a bare number rather than printing it — a figure whose provenance nobody
    recorded is exactly what this site exists not to show — so everything the page displays goes
    through here.

    Args:
        value: The figure, or None when genuinely unavailable.
        unit: What it counts.
        provenance: `measured`, `estimated` or `unknown`.
        source: Which artifact it came from.

    Returns:
        The wrapped value.
    """
    return {"value": value, "unit": unit, "provenance": provenance, "source": source}


def collect(bundle: Path, results: Path) -> dict:
    """Read every published figure the page needs.

    Args:
        bundle: `submission_artifacts/`.
        results: `results/`.

    Returns:
        The bundle the page imports.

    Raises:
        SystemExit: If a run has not been done. A page built from an absent run would render zeros
            and look like a working page reporting a broken system.
    """
    evidence_path = bundle / "evidence.json"
    if not evidence_path.is_file():
        raise SystemExit(
            f"no evidence at {evidence_path} — run run_demo.py first. Building the page without it "
            f"would publish zeros that look like measurements."
        )

    evidence = json.loads(evidence_path.read_text(encoding="utf-8"))
    rows = {row["requirement"]: row for row in evidence["requirements"]}

    corpus_path = results / "corpus_build.json"
    corpus = json.loads(corpus_path.read_text(encoding="utf-8")) if corpus_path.is_file() else {}

    packing = rows["packing_correctness"]["numbers"]
    replay = rows["replay"]["numbers"]
    crash = rows["crash_recovery"]["numbers"]
    opus = rows["opus_audit_trail"]["numbers"]
    firewall = rows["evaluation_firewall"]["numbers"]
    rate = rows["throughput"]["numbers"]

    ledger_lines = sum(
        1
        for path in sorted((bundle / "ledger").glob("*.jsonl"))
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    )

    # One decision row per candidate, read from the logs rather than from the summary — the page
    # renders a mark per candidate, so it needs the rows, and counting them here is also a check
    # that the summary and the logs agree.
    passes = []
    for path in sorted((bundle / "opus").glob("opus-*.jsonl")):
        lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
        header, decisions = json.loads(lines[0]), [json.loads(ln) for ln in lines[1:]]
        passes.append(
            {
                "id": header["pass_id"],
                "offered": header["offered"],
                "served": header["served"],
                "reserved": header["reserved"],
                "temperature": header["temperature"],
                "noise_dominance": header["noise_dominance"],
                "floors": header["floors"],
                "decisions": [
                    {
                        "lane": d["lane"],
                        "decision": d["decision"],
                        "score": round(d["raw_score"], 2),
                        "rank": d["rank"],
                        "flip": d["flip_rate"],
                        "reason": d["reason"],
                    }
                    for d in decisions
                ],
            }
        )

    return {
        "run": {
            "id": evidence.get("run_id"),
            "fingerprint": evidence.get("config_fingerprint"),
            "requirements_met": sum(1 for r in evidence["requirements"] if r["status"] == "met"),
            "requirements_total": len(evidence["requirements"]),
        },
        "ledger": {
            "events": _value(ledger_lines, "events", source="submission_artifacts/ledger/"),
            "microbatches": _value(packing["microbatches"], "microbatches"),
            "tokens": _value(packing["tokens"], "tokens"),
            "loss_tokens": _value(packing["loss_tokens"], "tokens"),
            "loss_utilization": _value(round(packing["loss_utilization"], 4), "share"),
        },
        "replay": {
            "checked": _value(replay["checked"], "microbatches"),
            "interval": replay.get("interval"),
            "matched": _value(replay.get("matched", replay["checked"]), "microbatches"),
        },
        "crash": {
            "checkpoint": crash["checkpoint"],
            "reexecuted": _value(crash["reexecuted"], "microbatches"),
            "ids_match": crash["ids_match"],
            "cut": crash["cut"],
            "events": _value(crash["events"], "events"),
        },
        "opus": {
            "candidates": _value(opus["candidates"], "candidates"),
            "passes": _value(opus["passes"], "passes"),
            "decisions": opus["decisions"],
            "by_lane": opus["by_lane"],
            "defer_rate": _value(opus["defer_rate"], "share"),
            "noise_dominance": _value(opus.get("noise_dominance"), "ratio"),
            "redundancy_share": _value(opus.get("redundancy_share"), "share"),
            "floors": opus.get("floors"),
            "floors_unsupplied": opus.get("floors_unsupplied") or [],
            "logs": passes,
        },
        "firewall": {
            "trainable": _value(firewall["trainable"], "shards"),
            "blocked": _value(firewall["blocked"], "shards"),
            "leaked": firewall["blocked_shards_consumed"],
        },
        "throughput": {
            "tokens_per_second": _value(round(rate["tokens_per_second"]), "tokens/s"),
            "ranks": _value(rate["ranks"], "ranks"),
            "seconds": _value(round(rate["seconds"], 3), "s"),
        },
        "corpus": {
            "shards": _value(corpus.get("shards"), "shards"),
            "train_tokens": _value(corpus.get("train_tokens"), "tokens"),
            "heldout_tokens": _value(corpus.get("heldout_tokens"), "tokens"),
            "epochs": _value(corpus.get("epochs_of_supply"), "ratio"),
            "compliant": corpus.get("mixture", {}).get("compliant"),
            "floors_held": corpus.get("mixture", {}).get("floors_held"),
            "consumed": corpus.get("mixture", {}).get("consumed", {}),
        },
        "plan": {
            "lane_shares": dict(spec.LANE_SHARES),
            "floors": dict(spec.FLOORS),
            "decisions": list(spec.DECISIONS),
            "requirements": list(spec.REQUIREMENTS),
            "sequence": list(spec.REQUIRED_SEQUENCE),
        },
    }


def render(payload: dict) -> str:
    """Turn the payload into the module the page imports.

    Args:
        payload: What `collect` produced.

    Returns:
        The file contents.
    """
    body = json.dumps(payload, indent=1, sort_keys=True, ensure_ascii=False, default=str)
    return f"{HEADER}export const BUNDLE = Object.freeze({body});\n"


def main() -> int:
    """Write `web/data.js`, or check it is current.

    Returns:
        Process exit status. Non-zero under `--check` when the file is stale.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, default=BUNDLE_DIR)
    parser.add_argument("--results", type=Path, default=RESULTS_DIR)
    parser.add_argument("--out", type=Path, default=WEB_DIR / "data.js")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the file on disk differs from what this run would write",
    )
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stdout)

    contents = render(collect(args.bundle, args.results))

    if args.check:
        if not args.out.is_file():
            logger.error("%s does not exist — run this without --check", args.out)
            return 1
        if args.out.read_text(encoding="utf-8") != contents:
            logger.error(
                "%s is stale: the page would render figures the current run did not produce",
                args.out,
            )
            return 1
        logger.info("%s matches the current run", args.out)
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(contents, encoding="utf-8")
    logger.info("%s (%s bytes)", args.out, f"{len(contents):,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
